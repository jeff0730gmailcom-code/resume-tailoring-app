"""AI-powered resume tailoring service — Steps 4-5 of the pipeline (prompt
build + the single OpenAI request).

Tailoring policy: employer names, employment dates, education, and
certifications are IDENTITY FACTS spliced verbatim from MasterCvData -
never sent to or generated by the AI. Everything else - the professional
summary, the full Skills list, and every job's experience bullets - is
generated by the AI to best fit the target job description, not limited to
what the candidate's real CV already shows for that job/skillset (see
app/prompts/resume_tailor_prompt.py for the exact instructions).

Two prompt/output paths:
- Structured (preferred, when MasterCvData.is_structured): builds a compact
  prompt from pre-parsed CV/JD data and asks for TailoredDynamicContent
  (summary + skills + per-job title/bullets). Job title/company/dates are
  spliced from MasterCvData afterward, overriding anything the AI wrote for
  them. Any bullet shortfall is padded from other JD-driven jobs' bullets,
  then deterministic JD-derived filler as a last resort - never from the
  candidate's real original bullets, since bullets are meant to be fully
  JD-driven now.
- Fallback (raw CV text): used when structuring wasn't confident (PDF
  upload, or an unusual DOCX layout) - asks the model for the full
  TailoredResumeContent schema directly from the whole CV text.

Uses AsyncOpenAI rather than the sync client so the multi-second network
round trip never blocks FastAPI's event loop - with a sync client, one
in-flight tailoring request would stall every other request the server is
handling (including unrelated /health checks), which matters at scale.
"""
